#ifndef ASCII_H
#define ASCII_H

/* ASCII colors*/
#define ASCII_BLACK             "\033[30m"
#define ASCII_RED               "\033[31m"
#define ASCII_GREEN             "\033[32m"
#define ASCII_YELLOW            "\033[33m"
#define ASCII_BLUE              "\033[34m"
#define ASCII_MAGENTA           "\033[35m"
#define ASCII_CYAN              "\033[36m"
#define ASCII_WHITE             "\033[37m"
#define ASCII_BLACK_BOLD        "\033[1;30m"
#define ASCII_RED_BOLD          "\033[1;31m"
#define ASCII_GREEN_BOLD        "\033[1;32m"
#define ASCII_YELLOW_BOLD       "\033[1;33m"
#define ASCII_BLUE_BOLD         "\033[1;34m"
#define ASCII_MAGENTA_BOLD      "\033[1;35m"
#define ASCII_CYAN_BOLD         "\033[1;36m"
#define ASCII_WHITE_BOLD        "\033[1;37m"

#define ASCII_CLEAR_LINE        "\r\033[2K"
#define ASCII_RESET             "\033[0m"

#endif
